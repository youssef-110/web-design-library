// Builds INDEX.md and index.json from the front matter of styles/*.md.
// Run: node scripts/build-index.mjs   (add --check to fail on invalid entries)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'styles');
const REQUIRED = ['name', 'url', 'category', 'theme', 'mood', 'signature', 'palette', 'fonts', 'radius', 'checked'];
const SECTIONS = ['## Colour', '## Type', '## Layout and rhythm', '## Why it does not look generic', '## Steal this', '## Not for'];

// Minimal parser for the flat front matter this library uses (scalars, [a, b] lists, lists of { k: "v" } maps).
const scalar = (v) => v.trim().replace(/\s+#.*$/, '').replace(/^["']|["']$/g, '');
const inlineMap = (s) => Object.fromEntries([...s.matchAll(/(\w+):\s*("([^"]*)"|[^,}]+)/g)].map((m) => [m[1], (m[3] ?? m[2]).trim()]));
function parse(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return null;
  const out = {};
  let key = null;
  for (const line of m[1].split(/\r?\n/)) {
    const item = line.match(/^\s+-\s*\{(.*)\}\s*$/);
    if (item && key) { out[key].push(inlineMap(item[1])); continue; }
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    key = kv[1];
    const v = kv[2];
    if (v === '') out[key] = [];
    else if (v.startsWith('[')) out[key] = v.replace(/^\[|\].*$/g, '').split(',').map((s) => s.trim()).filter(Boolean);
    else out[key] = scalar(v);
  }
  return out;
}

const errors = [];
const entries = readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((file) => {
  const text = readFileSync(join(dir, file), 'utf8');
  const fm = parse(text);
  if (!fm) { errors.push(`${file}: no front matter`); return null; }
  for (const k of REQUIRED) if (fm[k] === undefined || fm[k].length === 0) errors.push(`${file}: missing ${k}`);
  for (const s of SECTIONS) if (!text.includes(s)) errors.push(`${file}: missing section "${s}"`);
  for (const p of fm.palette ?? []) if (!/^#[0-9a-f]{6}$/i.test(p.hex ?? '')) errors.push(`${file}: bad hex ${p.hex}`);
  if (/[—–]/.test(text)) errors.push(`${file}: contains an em or en dash`);
  if (fm.stack && fm.stack.length && !text.includes('## Rebuild notes')) errors.push(`${file}: has a stack but no "## Rebuild notes" section`);
  return { slug: file.replace(/\.md$/, ''), ...fm };
}).filter(Boolean);

if (errors.length) console.error(errors.join('\n'));
if (process.argv.includes('--check') && errors.length) process.exit(1);

writeFileSync(join(root, 'index.json'), JSON.stringify(entries, null, 2) + '\n');

const byCat = Object.groupBy(entries, (e) => e.category);
const swatch = (e) => (e.palette ?? []).slice(0, 5).map((p) => `\`${p.hex}\``).join(' ');
let md = `# Index\n\n${entries.length} references. Generated by \`scripts/build-index.mjs\`; do not edit by hand.\n`;
for (const cat of Object.keys(byCat).sort()) {
  md += `\n## ${cat}\n\n| Site | Theme | Mood | Signature | Palette |\n|---|---|---|---|---|\n`;
  for (const e of byCat[cat]) md += `| [${e.name}](styles/${e.slug}.md) | ${e.theme} | ${(e.mood ?? []).join(', ')} | ${e.signature} | ${swatch(e)} |\n`;
}
// entries with measured motion stacks, grouped by tool, so an agent can find a reference by technique
const withStack = entries.filter((e) => Array.isArray(e.stack) && e.stack.length);
if (withStack.length) {
  const byTool = {};
  for (const e of withStack) for (const t of e.stack) (byTool[t] ??= []).push(e);
  md += `\n## By motion stack\n\nEntries whose motion was measured on the live site. Each has a "Rebuild notes" section with timings, easing and scroll ranges.\n\n| Stack | Entries |\n|---|---|\n`;
  for (const t of Object.keys(byTool).sort((a, b) => byTool[b].length - byTool[a].length || a.localeCompare(b))) md += `| ${t} | ${byTool[t].map((e) => `[${e.name}](styles/${e.slug}.md)`).join(', ')} |\n`;
}
writeFileSync(join(root, 'INDEX.md'), md);
console.log(`${entries.length} entries, ${errors.length} problems`);
